def process_file(filepath):
    with open(filepath, 'rb') as f:
        raw = f.read()
    
    changed = False
    for old_bytes, new_bytes in [(k.encode('utf-8'), v.encode('utf-8')) for k, v in REPLACE.items()]:
        if old_bytes in raw:
            raw = raw.replace(old_bytes, new_bytes)
            changed = True
    
    if changed:
        with open(filepath, 'wb') as f:
            f.write(raw)
        return True
    return False

